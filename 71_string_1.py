#string related library functions
name = "The Easylearn Academy"

print("Length of the string is:", len(name))
print("The string in upper case is:", name.upper())
print("The string in lower case is:", name.lower())
print("The string in title case is:", name.title())
print("is this string in lower case?", name.islower())
print("is this string in upper case?", name.isupper())
print("is this string in title case?", name.istitle())
print("is this alphanumeric?", name.isalnum())
print("is this string has only numbers ?", name.isnumeric())