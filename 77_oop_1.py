#crete class 
class MyMath:
    #define methods(function)
    def add(self):
        print("I can do addition")
    def sub(self):
        print("I can do subtraction")
    def mul(self):
        print("I can do multiplication")
    def div(self):
        print("I can do division")
    
#we must create object to call methods of the MyMath class
#object = ClassName()
m1 = MyMath() #we have to create object then we can call method using object
m1.add()
m1.sub()
m1.mul()
m1.div()

m2 = MyMath()
m2.add()
m2.sub()
m2.mul()
